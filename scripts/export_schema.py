"""Write database/psupulse.sql — the file to IMPORT in phpMyAdmin.

It creates the `psupulse` database, every table, and the default admin account
(ADMIN_USERNAME / ADMIN_PASSWORD from .env). No database connection is needed.

Usage:  python scripts/export_schema.py
"""
import os

import _bootstrap  # noqa: F401
from sqlalchemy.dialects import mysql
from sqlalchemy.schema import CreateTable
from werkzeug.security import generate_password_hash

from app import create_app
from app.extensions import db

OUT = os.path.join(_bootstrap.PROJECT_ROOT, "database", "psupulse.sql")


def main():
    app = create_app()
    with app.app_context():
        dialect = mysql.dialect()
        parts = [
            "-- PSU Pulse schema for XAMPP (MariaDB). Generated by scripts/export_schema.py",
            "-- Safe to import more than once: existing tables and data are left untouched.",
            "CREATE DATABASE IF NOT EXISTS `psupulse` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
            "USE `psupulse`;",
            "",
        ]
        for table in db.metadata.sorted_tables:
            ddl = str(CreateTable(table, if_not_exists=True).compile(dialect=dialect)).strip()
            parts.append(f"{ddl} ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n")
            for index in sorted(table.indexes, key=lambda ix: ix.name):  # stable order between runs
                cols = ", ".join(f"`{c.name}`" for c in index.columns)
                unique = "UNIQUE " if index.unique else ""
                parts.append(f"CREATE {unique}INDEX IF NOT EXISTS `{index.name}` ON `{table.name}` ({cols});")
            if table.indexes:
                parts.append("")

        username = os.getenv("ADMIN_USERNAME", "admin")
        password_hash = generate_password_hash(os.getenv("ADMIN_PASSWORD", "admin12345"))
        parts += [
            "-- Default administrator (change the password after the first sign-in)",
            "INSERT IGNORE INTO users (username, full_name, password_hash, role, active, created_at) "
            f"VALUES ('{username}', 'System Administrator', '{password_hash}', 'admin', 1, NOW());",
            "",
        ]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
